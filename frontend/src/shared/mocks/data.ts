function buildOctoberCalendar(): CalendarOccurrence[] {
  const items: CalendarOccurrence[] = [];

  for (let day = 1; day <= 31; day += 1) {
    const occurrenceDate = `2026-10-${String(day).padStart(2, "0")}`;

    dailyOperations.forEach((operation, index) => {
      const fulfilled = day % 6 === 0 && index === 0;
      const taskId =
        day === 30 && index === 0
          ? "b1000000-0000-4000-8000-000000000001"
          : day === 29 && index === 1
            ? "b1000000-0000-4000-8000-000000000002"
            : null;

      items.push({
        id: `cal-${day}-${index + 1}`,
        occurrenceDate,
        equipmentId: operation.equipmentId,
        equipmentName: operation.equipmentName,
        operationCode: operation.code,
        operationTitle: operation.title,
        maintenanceType: "ТО1",
        status: fulfilled ? "fulfilled" : "planned",
        isOverdue: day < 30 && !fulfilled,
        requiresInput: false,
        taskId,
      });
    });
  }

  return items;
}

