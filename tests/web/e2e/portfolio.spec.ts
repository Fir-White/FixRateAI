    await page.reload();await expect(saved).toContainText('Выпуск заданий с использованием действующих регламентов');
    await steps.getByRole('button',{name:'Состав работ',exact:true}).click();
    await expect(saved).toContainText(/Размещено 5(?:\.0+)? из 5(?:\.0+)?/);
    await saved.getByRole('button',{name:'История версий плана'}).click();
    await saved.getByRole('button',{name:/Версия 1 ·/}).click();
    await expect(page).toHaveURL(/portfolio_revision=1/);
    await expect(saved).toContainText('Открыта версия для просмотра');
    await expect(saved.getByRole('button',{name:'Изменить условия расчёта'})).toHaveCount(0);
    await page.goBack();await expect(page).toHaveURL(/portfolio_revision=3/);
    await expect(saved).toContainText(/Размещено 5(?:\.0+)? из 5(?:\.0+)?/);
